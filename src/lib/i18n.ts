// Labels fall back to English when a language is missing one entry.
export function typeLabel(t: Strings, key: string): string {
  return t.types[key] ?? en.types[key] ?? key;
}
export function interestLabel(t: Strings, key: string): string {
  return t.interestNames[key] ?? en.interestNames[key] ?? key;
}

