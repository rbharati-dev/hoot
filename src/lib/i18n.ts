/** A game's name in the reader's language. */
export function gameName(t: Strings, g: GameId): string {
  const names: Record<GameId, string> = {
    trivia: t.trivia, tune: t.nameTune, crossword: t.crossword, wordsearch: t.wordsearch, scramble: t.wordscramble, hangman: t.hangman,
    solitaire: t.solitaire, sudoku: t.sudoku, pattern: t.pattern, quickmath: t.quickmath, chess: t.chess, checkers: t.checkers,
  };
  return names[g];
}
